create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null default '',
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.cultural_contents (
  id bigint generated by default as identity primary key,
  category text not null,
  title text not null,
  summary text not null,
  content text not null default '',
  image_url text,
  video_url text,
  created_at timestamptz not null default now()
);

alter table public.cultural_contents
  add column if not exists content text not null default '';

create table if not exists public.cultural_music (
  id text primary key default gen_random_uuid()::text,
  title text not null,
  artist text not null,
  genre text not null,
  region text not null default '',
  year text not null default '',
  duration text not null default '',
  image_url text not null default '',
  youtube_id text not null default '',
  description text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.cultural_events (
  id bigint generated by default as identity primary key,
  title text not null,
  event_date date not null,
  event_time time,
  location text not null,
  description text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.favorites (
  user_id uuid not null references auth.users (id) on delete cascade,
  item_id text not null,
  created_at timestamptz not null default now(),
  primary key (user_id, item_id)
);

create table if not exists public.music_favorites (
  user_id uuid not null references auth.users (id) on delete cascade,
  track_id text not null,
  created_at timestamptz not null default now(),
  primary key (user_id, track_id)
);

create table if not exists public.user_rate_limits (
  user_id uuid primary key references auth.users (id) on delete cascade,
  window_started_at timestamptz not null,
  request_count integer not null check (request_count > 0)
