create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create or replace function public.consume_user_rate_limit(
  p_user_id uuid,
  p_limit integer,
  p_window_seconds integer
)
returns table (allowed boolean, retry_after integer)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_window_started timestamptz;
  v_request_count integer;
  v_retry_after integer;
begin
  if p_user_id is null
    or p_limit is null or p_window_seconds is null
    or p_limit < 1 or p_limit > 100
    or p_window_seconds < 1 or p_window_seconds > 86400 then
    raise exception 'Invalid rate limit parameters';
  end if;

  insert into public.user_rate_limits as current_limit (user_id, window_started_at, request_count)
  values (p_user_id, v_now, 1)
  on conflict (user_id) do update
  set window_started_at = case
        when current_limit.window_started_at <= v_now - make_interval(secs => p_window_seconds)
          then v_now
        else current_limit.window_started_at
      end,
      request_count = case
        when current_limit.window_started_at <= v_now - make_interval(secs => p_window_seconds)
          then 1
        else least(current_limit.request_count + 1, p_limit + 1)
      end
  returning window_started_at, request_count
  into v_window_started, v_request_count;

  v_retry_after := case
    when v_request_count <= p_limit then 0
    else greatest(
      1,
      ceil(extract(epoch from (
        v_window_started + make_interval(secs => p_window_seconds) - v_now
      )))::integer
    )
  end;

  return query select v_request_count <= p_limit, v_retry_after;
end;
$$;
revoke all on function public.consume_user_rate_limit(uuid, integer, integer) from public, anon, authenticated;
grant execute on function public.consume_user_rate_limit(uuid, integer, integer) to service_role;

